const {chromium}=require('playwright');
const fs=require('node:fs');
(async()=>{
 fs.mkdirSync('artifacts/recordings',{recursive:true});
 fs.mkdirSync('docs/screenshots',{recursive:true});
 const browser=await chromium.launch();
 const context=await browser.newContext({viewport:{width:1280,height:800},recordVideo:{dir:'artifacts/recordings',size:{width:1280,height:800}}});
 const page=await context.newPage();
 const base=process.env.NEXO_URL||'http://localhost:8092';
 await page.goto(base,{waitUntil:'networkidle'});
 await page.locator('img').evaluateAll(async imgs=>{imgs.forEach(i=>i.loading='eager');await Promise.all(imgs.map(i=>i.decode()));});
 await page.screenshot({path:'docs/screenshots/overview-desktop.png'});
 await page.waitForTimeout(900);
 await page.locator('#colecao').scrollIntoViewIfNeeded();
 await page.waitForTimeout(900);
 await page.goto(base+'/produto/headphone-studio-one/',{waitUntil:'networkidle'});
 await page.locator('select[name="attribute_cor"]').selectOption({label:'Areia'});
 await page.waitForTimeout(700);
 await page.locator('.single_add_to_cart_button').click();
 await page.waitForLoadState('networkidle');
 await page.goto(base+'/carrinho/',{waitUntil:'networkidle'});
 await page.locator('#coupon_code').fill('NEXO10');
 await page.locator('[name="apply_coupon"]').click();
 await page.waitForSelector('.cart-discount');
 await page.waitForTimeout(700);
 await page.screenshot({path:'docs/screenshots/cart-desktop.png',fullPage:true});
 await page.goto(base+'/finalizar-compra/',{waitUntil:'networkidle'});
 await page.waitForTimeout(1100);
 const video=page.video();
 await context.close();
 await video.saveAs('artifacts/recordings/portfolio.webm');
 const mobile=await browser.newPage({viewport:{width:390,height:844}});
 await mobile.goto(base,{waitUntil:'networkidle'});
 await mobile.screenshot({path:'docs/screenshots/overview-mobile.png'});
 await browser.close();
 console.log('Portfolio screenshots and actual browser recording captured.');
})();
